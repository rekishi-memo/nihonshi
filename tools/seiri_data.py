# 書式： C(id, 見出し, 色, [ブロック…], terms=[授業にこの語（《》）が need 個以上あれば、その授業からこのカードへ飛ぶボタンを出す], need=2)
#   ブロック： ('v',[箱,'↓ラベル',箱,…]) たての流れ ／ ('h',[箱,'→ラベル',箱,…]) よこの流れ ／ ('t',[見出し…],[[行]…]) 表
#             ('tree',根,[枝…]) 枝分かれ ／ ('p',文) ／ ('s',小さい注) ／ ('lb',ラベル,文)
#   文の中の《語》は赤い重要語。
# G＝授業（カードのまとまり）。順番どおりに並ぶ。
G=[]
def grp(no,nav,title,theme): G.append(dict(no=no,nav=nav,title=title,theme=theme,cards=[]))
def C(id,title,color,blocks,terms=(),need=2): G[-1]['cards'].append(dict(id=id,title=title,color=color,blocks=blocks,terms=list(terms),need=need))

