O=(136.0,36.0); KX=111.32*math.cos(math.radians(O[1])); KY=110.95
def P(lon,lat):
    if lon<-25: lon+=360   # 西半球は東へ（日本中心の世界地図）
    return [round((lon-O[0])*KX,2),round((lat-O[1])*KY,2)]
BBOX=(108.0,150.0,22.0,49.0)

def ground(bbox=BBOX,tol=1.6,ctol=4.0,minarea=3):
    """陸の形（ぬり）と海岸線（県境をのぞく）。日本はこまかめ、大陸はあらめ"""
    lon0,lon1,lat0,lat1=bbox; G=_geo(); fills=[]; coasts=[]; jpfills=[]
    from collections import Counter
    cnt=Counter()
    for R in G['jp']:
        for i in range(len(R)):
            a,b=tuple(R[i-1]),tuple(R[i]); cnt[(min(a,b),max(a,b))]+=1
    inb=lambda p:lon0<=p[0]<=lon1 and lat0<=p[1]<=lat1
    def flat(K): return [v for x,z in K for v in (round(x,1),round(z,1))]
    def pk(q): return ((q[0]-O[0])*KX,(q[1]-O[1])*KY)
    for key in ('land','jp'):
        t=tol if key=='jp' else ctol
        for R in G[key]:
            xs=[p[0] for p in R]; ys=[p[1] for p in R]
            if max(xs)<lon0 or min(xs)>lon1 or max(ys)<lat0 or min(ys)>lat1: continue
            C=_clip([tuple(p) for p in R],lon0,lat0,lon1,lat1)
            if len(C)<3: continue
            K=_dp([pk(q) for q in C]+[pk(C[0])],t)[:-1]
            if len(K)<3: continue
            a=abs(sum(K[i-1][0]*K[i][1]-K[i][0]*K[i-1][1] for i in range(len(K))))/2
            if a<minarea: continue
            fills.append(flat(K))
            if key=='jp': jpfills.append(R)
            n=len(R); co=[(cnt[(min(tuple(R[i-1]),tuple(R[i])),max(tuple(R[i-1]),tuple(R[i])))]==1) if key=='jp' else True for i in range(n)]
            if not any(co): continue
            start=0 if all(co) else next(i for i in range(n) if not co[i])
            run=[]
            def flush():
                if len(run)>1:
                    L=_dp([pk(q) for q in run],t)
                    if len(L)>1: coasts.append(flat(L))
            for j in range(n+1):
                i=(start+j)%n
                if co[i] and inb(R[i-1]) and inb(R[i]):
                    if not run: run=[tuple(R[i-1])]
                    run.append(tuple(R[i]))
                else:
                    flush(); run=[]
            flush()
    return fills,coasts,jpfills

def _inside(lon,lat,R):
    c=False; n=len(R)
    for i in range(n):
        x1,y1=R[i-1]; x2,y2=R[i]
        if (y1>lat)!=(y2>lat) and lon<x1+(lat-y1)*(x2-x1)/(y2-y1): c=not c
    return c

def trees(jpfills,n=320,seed=5):
    """日本の陸の上に、森の印を散らす。東日本（落葉広葉樹林）と西日本（照葉樹林）で色を分ける"""
    import random; r=random.Random(seed); out=[]
    boxes=[(R,min(p[0] for p in R),max(p[0] for p in R),min(p[1] for p in R),max(p[1] for p in R)) for R in jpfills]
    tries=0
    while len(out)<n and tries<40000:
        tries+=1; lon=r.uniform(129.5,145.5); lat=r.uniform(31.0,45.3)
        if lat>41.6 or lon>142: continue      # 北海道は森の色分けの話に入れない
        if any(b[1]<=lon<=b[2] and b[3]<=lat<=b[4] and _inside(lon,lat,b[0]) for b in boxes):
            east=1 if (lon>137.6 or lat>36.3) else 0
            if 136.6<lon<138.6 and r.random()<0.5: east=1-east
            out.append([*P(lon,lat),east])
    return out

