def rank_for_packs(packs):
    """本文の語・一問一答の答え・用語集の語すべてに A〜D・X をつける"""
    rank,fr,wide=build()
    def plain(h): return re.sub(r'<[^>]+>','',re.sub(r'<rt>[^<]*</rt>','',h or ''))
    main=set(); deep=set(); qa={}; terms=set()
    for p in packs:
        for l in p.get('lessons',[]):
            h=l.get('html') or ''
            hd=''.join(re.findall(r"<div class='deep'>[\s\S]*?</div>",h))
            hm=re.sub(r"<div class='deep'>[\s\S]*?</div>",'',h)
            for t in re.findall(r"<span class='kw'>([\s\S]*?)</span>",hm): main.add(plain(t))
            for t in re.findall(r"<span class='kw'>([\s\S]*?)</span>",hd+(l.get('colHtml') or '')): deep.add(plain(t))
        for q in p.get('quiz',[]):
            for w in (q.get('mark'),q.get('a')):
                if w: qa.setdefault(re.sub(r'[（(].*?[）)]','',w).strip(),[]).append(q.get('d',2))
        for t in p.get('terms',[]) or []: terms.add(t.get('term'))
    universe=main|deep|set(qa)|terms
    rank=expand(rank)
    LOW={'A':'B','B':'C','C':'C','D':'D'}
    keys=sorted((k for k,v in rank.items() if v!='X' and len(k)>=3),key=len)
    for w in universe:
        if not w or w in rank: continue
        n=fr(w)
        # 長い語の一部（平等院⊂平等院鳳凰堂、白村江⊂白村江の戦い）・長い言い方（稲荷山古墳の鉄剣）は、もとの語より一段下げる
        if not wide(w) and len(w)>=3:
            hit=next((k for k in keys if k.startswith(w) and len(k)<=len(w)+6),None) or next((k for k in reversed(keys) if w.startswith(k) and len(w)<=len(k)+6),None)
            if hit: rank[w]=LOW[rank[hit]]; continue
        only_deep=(w in deep and w not in main)
        if wide(w): rank[w]='B'
        elif w in qa or n==1 or w in terms: rank[w]='D' if only_deep else 'C'
        elif only_deep: rank[w]='D'
        else: rank[w]='X'
    return rank

