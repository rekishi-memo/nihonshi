def lineup(add,win,names,c='#46607e',cols=None):
    """人を順に出す（左から右へ、前後にずらす）。名前の札つき"""
    n=len(names); dt=max(0.6,(win[1]-win[0]-1.6)/n)
    for i,nm in enumerate(names):
        x=round(-3.0+6.0*i/max(1,n-1),2); z=1.3 if i%2==0 else -0.7; t=round(win[0]+0.3+i*dt,2)
        add(k='crowd',n=1,r=0,h=0.85,c=(cols[i] if cols else c),rel=[x,z],on=[t,win[1]],seed=i+1)
        add(k='tag',s=nm,rel=[x,z],lift=(46 if i%2==0 else 34),on=[t+0.1,win[1]])
